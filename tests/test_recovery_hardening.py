def test_unreadable_event_does_not_hide_independent_intent(fixture):
    data = fixture()
    approval = approve(data, plan(data))
    execute(data, approval)
    ledger = Ledger(data["profile"])
    result = ledger.read_event(approval, 0, "result")
    # Unsafe permission is rejected even though the owner could physically read it.
    path = ledger.store.path("receipts", result["receipt_digest"])
    path.chmod(0o644)
    inspected, code = command(data, "inspect", approval, "--kind", "reconstruction")
    assert code == 2
    record = inspected["interruption_evidence"][0]
    assert record["intent"]["kind"] == "shutdown" and "result" not in record
    assert record["accounting"]["result"] == "invalid-or-unreadable"
    assert path.stat().st_mode & 0o777 == 0o644  # no permission repair


